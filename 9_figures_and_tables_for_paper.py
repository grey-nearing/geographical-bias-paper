def _safe_unlink(path: str):
  if os.path.lexists(path):
    if os.path.isdir(path) and not os.path.islink(path):
      shutil.rmtree(path)
    else:
      os.unlink(path)


def _normalize_gauge_id(val) -> str:
  """Removes top-level CARAVAN_ prefix while preserving sub-dataset IDs."""
  norm = str(val).strip().upper()
  if norm.startswith('CARAVAN_'):
    return norm[len('CARAVAN_') :]
  return norm


def _normalize_hybas_id(series: pd.Series) -> pd.Series:
  """Normalizes HydroBASINS IDs to 'hybas_<int>' strings."""
  nums = pd.to_numeric(
      series.astype(str)
      .str.replace('hybas_', '', regex=False)
      .str.replace(r'\.0$', '', regex=True),
      errors='coerce',
  )
  return 'hybas_' + nums.astype('Int64').astype(str)


def _load_world_gdf() -> gpd.GeoDataFrame:
  """Loads Natural Earth country polygons with harmonized names and ISO3 codes."""
  with gfile.Open(file_paths.NATURAL_EARTH_PATH, 'rb') as f:
    world = gpd.read_file(f)
  if 'name' in world.columns:
    world = world[world['name'] != 'Antarctica'].copy()
  world = world.dropna(subset=[world.geometry.name])
  world = world[world.is_valid & (~world.is_empty)].copy()
  world['map_name'] = world['name'].replace(file_paths.country_name_map)
  iso_fix = {'France': 'FRA', 'Norway': 'NOR'}
  world['iso_clean'] = [
      iso_fix.get(mname, str(iso).strip())
      for mname, iso in zip(world['map_name'], world.get('iso_a3', ''))
  ]
  return world


def _load_inform_vulnerability(world_gdf: gpd.GeoDataFrame) -> pd.Series:
  """Maps harmonized country names to INFORM 2026 Socioeconomic Vulnerability."""
  country_to_iso = dict(zip(world_gdf['map_name'], world_gdf['iso_clean']))
  with gfile.Open(file_paths.RISK_FILE, 'rt') as f:
    df_inform = pd.read_csv(io.StringIO(f.read()), skiprows=[0, 2])
  df_inform['ISO3'] = df_inform['ISO3'].astype(str).str.strip()
  df_inform['COUNTRY_CLEAN'] = (
      df_inform['COUNTRY']
      .astype(str)
      .str.strip()
      .replace(file_paths.country_name_map)
  )
  df_inform['VULN_NUM'] = pd.to_numeric(
      df_inform['VULNERABILITY'], errors='coerce'
  )
  iso_vuln = (
      df_inform.dropna(subset=['ISO3', 'VULN_NUM'])
      .drop_duplicates('ISO3')
      .set_index('ISO3')['VULN_NUM']
  )
  name_vuln = (
      df_inform.dropna(subset=['COUNTRY_CLEAN', 'VULN_NUM'])
      .drop_duplicates('COUNTRY_CLEAN')
      .set_index('COUNTRY_CLEAN')['VULN_NUM']
  )
  all_countries = sorted(
      set(country_to_iso.keys()).union(set(name_vuln.index))
  )
  out = {}
  for c in all_countries:
    iso = country_to_iso.get(c)
    val = iso_vuln.get(iso, np.nan) if iso else np.nan
    if pd.isna(val):
      val = name_vuln.get(c, np.nan)
    out[c] = val
  return pd.Series(out, name='Vulnerability')


def _load_hybas_latlon() -> pd.DataFrame:
  """Loads watershed representative coordinates indexed by 'hybas_<int>'."""
  with gfile.Open(file_paths.HYBAS_LATLON_PATH, 'rt') as f:
    df_ll = pd.read_csv(f, index_col=0)
  lat_col = next(c for c in df_ll.columns if 'lat' in c.lower())
  lon_col = next(c for c in df_ll.columns if 'lon' in c.lower())
  out = pd.DataFrame({
      'hybas_id': _normalize_hybas_id(pd.Series(df_ll.index)).values,
      'lat': pd.to_numeric(df_ll[lat_col], errors='coerce').values,
      'lon': pd.to_numeric(df_ll[lon_col], errors='coerce').values,
  })
  return out.dropna(subset=['lat', 'lon']).drop_duplicates('hybas_id').set_index('hybas_id')


def _prepare_feature_map(feature_names: list[str]) -> dict[str, str]:
  """Maps raw and engineered feature names to the 8 canonical categories."""
  full_feature_map = {}
  for feat in feature_names:
    if feat in FEATURE_CLASSIFICATION:
      full_feature_map[feat] = FEATURE_CLASSIFICATION[feat]
    elif (
        'p_minus_pet' in feat
        or 'p_div_pet' in feat
        or 'et_deficit' in feat
        or 'precip' in feat
        or 'water_balance' in feat
        or 'aridity_ratio' in feat
    ):
      full_feature_map[feat] = 'Climate & Hydrology'
    elif 'soil_porosity' in feat:
      full_feature_map[feat] = 'Soil and Geology'
    elif 'twi_proxy' in feat or 'log_calculated_drain_area' in feat:
      full_feature_map[feat] = 'Topography'
    elif (
        'total_forest' in feat
        or 'total_arid_cover' in feat
        or 'forest_aridity' in feat
    ):
      full_feature_map[feat] = 'Land Cover'
    elif (
        'human_intensity' in feat
        or 'human_impact_density' in feat
        or 'log_pop' in feat
        or 'log_rev' in feat
        or 'log_ria' in feat
        or 'log_riv' in feat
    ):
      full_feature_map[feat] = 'Anthropogenic Factors'
    else:
      matched = False
      for base_feat in FEATURE_CLASSIFICATION:
        if base_feat in feat:
          full_feature_map[feat] = FEATURE_CLASSIFICATION[base_feat]
          matched = True
          break
      if not matched:
        full_feature_map[feat] = 'Other'
  return full_feature_map


def _save_png(fig: plt.Figure, out_dir: str, filename: str):
  out_path = os.path.join(out_dir, filename)
  _safe_unlink(out_path)
  with gfile.Open(out_path, 'wb') as f:
    fig.savefig(f, dpi=300, bbox_inches='tight')
  plt.close(fig)
  print(f"[{time.strftime('%H:%M:%S')}] Saved {out_path}")


def _save_csv(df: pd.DataFrame, out_dir: str, filename: str):
  out_path = os.path.join(out_dir, filename)
  _safe_unlink(out_path)
  with gfile.Open(out_path, 'wt') as f:
    df.to_csv(f, index=False)


